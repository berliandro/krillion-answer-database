#!/usr/bin/env python3
"""Emit build artefacts: manifest, generated JS normaliser, and v2 array JSON.

Legacy site JSON (search-data.json, krillion/krillion-data.json) is NEVER
written here. The v2 array format goes only to NEW filenames, so the running
site is untouched until a later phase switches its reader.

The generated normaliser is derived from the two sources of truth:
  * scripts/paraphrase_match.py -> normalise() (contraction/punctuation rules)
  * injection/bridge.py         -> REWRITES + the "beginning with" rule
Unknown rules cause a hard failure instead of a silently divergent JS copy.
"""
from __future__ import annotations

import ast
import hashlib
import json
import shutil
import sqlite3
from pathlib import Path

import config as cfg
import derive
from site_builder import LOADER_HTML, MORE_HTML, render_page

# Python regex literals in normalise() whose JS equivalent is known.
PY_JS_SUBS = {
    r"\s+": r"t = t.replace(/\s+/g, ' ');",
    r"[?!.,:;]+": r"t = t.replace(/[?!.,:;]+/g, ' ');",
}


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def file_digest(path: Path) -> str:
    return sha256_file(path) if path.exists() else ""


def etag() -> str:
    """sha256 of the concatenation of source answer JSONLs + corrections."""
    h = hashlib.sha256()
    for path in cfg.answer_files() + [cfg.CORRECTIONS]:
        if path.exists():
            h.update(path.read_bytes())
    return h.hexdigest()


def next_data_version() -> int:
    if not cfg.MANIFEST.exists():
        return cfg.INITIAL_DATA_VERSION
    try:
        old = json.loads(cfg.MANIFEST.read_text(encoding="utf-8"))
        return int(old.get("data_version", 0)) + 1
    except (ValueError, TypeError, OSError):
        return cfg.INITIAL_DATA_VERSION


def _normalise_parts() -> dict:
    """Extract the literal rules from paraphrase_match.normalise()."""
    tree = ast.parse(cfg.PARAPHRASE_SOURCE.read_text(encoding="utf-8"))
    fn = next(
        n for n in ast.walk(tree)
        if isinstance(n, ast.FunctionDef) and n.name == "normalise"
    )
    contractions = {}
    replaces = []
    subs = []
    for node in ast.walk(fn):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "contractions" for t in node.targets
        ):
            contractions = ast.literal_eval(node.value)
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        if node.func.attr == "replace" and len(node.args) >= 2:
            a, b = node.args[0], node.args[1]
            if isinstance(a, ast.Constant) and isinstance(b, ast.Constant):
                replaces.append((a.value, b.value))
        elif node.func.attr == "sub" and len(node.args) >= 3:
            pat, repl = node.args[0], node.args[1]
            if isinstance(pat, ast.Constant) and isinstance(repl, ast.Constant):
                subs.append((pat.value, repl.value))
    for pattern, _ in subs:
        if pattern not in PY_JS_SUBS:
            raise ValueError(
                f"paraphrase_match.normalise uses an unknown regex {pattern!r}; "
                "port it to emit.py PY_JS_SUBS before emitting JS"
            )
    return {"contractions": contractions, "replaces": replaces, "subs": subs}


def _rewrite_parts() -> list[tuple[str, str]]:
    """Extract bridge.py REWRITES rules (read-only)."""
    tree = ast.parse(cfg.BRIDGE_SOURCE.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "REWRITES" for t in node.targets
        ):
            rules = ast.literal_eval(node.value)
            return [(str(p), str(r)) for p, r in rules]
    raise ValueError("injection/bridge.py has no REWRITES assignment")


def _js_str(value: str) -> str:
    """JSON string syntax is valid JS string syntax (with ensure_ascii)."""
    return json.dumps(value, ensure_ascii=True)


def generated_norm_js() -> str:
    parts = _normalise_parts()
    rules = _rewrite_parts()
    bridge_src = cfg.BRIDGE_SOURCE.read_text(encoding="utf-8")
    if r"\bbeginning\s+with\b" not in bridge_src or "starting with" not in bridge_src:
        raise ValueError("bridge.py 'beginning with' rewrite rule not found")

    contractions_js = ",\n    ".join(
        f"[{_js_str(k)}, {_js_str(v)}]" for k, v in parts["contractions"].items()
    )
    replaces_js = "\n    ".join(
        f"t = t.replace({_js_str(a)}, {_js_str(b)});" for a, b in parts["replaces"]
    )
    # Both re.sub calls in normalise() are the same \s+ collapse; emit each
    # distinct rule at its position in the ported pipeline.
    subs_js = "\n    ".join(PY_JS_SUBS[p] for p, _ in parts["subs"])
    rewrites_js = ",\n    ".join(
        f"[/{p}/, {_js_str(r)}]" for p, r in rules
    )

    return f"""/* Generated by scripts/emit.py — DO NOT EDIT.
 * normalise rules: scripts/paraphrase_match.py (sha256 {sha256_file(cfg.PARAPHRASE_SOURCE)})
 * rewrite rules:   injection/bridge.py         (sha256 {sha256_file(cfg.BRIDGE_SOURCE)})
 * Contract: window.KrillionNorm = {{ norm, rewrite }}.
 */
(function (root) {{
  "use strict";
  var CONTRACTIONS = [
    {contractions_js}
  ];
  var REWRITES = [
    {rewrites_js}
  ];

  function escapeRegExp(s) {{
    return s.replace(/[.*+?^${{}}()|[\\]\\\\]/g, "\\\\$&");
  }}

  function norm(text) {{
    var t = String(text == null ? "" : text).trim().toLowerCase();
    {replaces_js}
    for (var i = 0; i < CONTRACTIONS.length; i++) {{
      var pair = CONTRACTIONS[i];
      t = t.replace(new RegExp("\\\\b" + escapeRegExp(pair[0]) + "\\\\b", "g"), pair[1]);
    }}
    {subs_js}
    return t.replace(/\\s+/g, " ").trim();
  }}

  function rewrite(text) {{
    var q = norm(text);
    for (var j = 0; j < REWRITES.length; j++) {{
      if (REWRITES[j][0].test(q)) {{
        q = q.replace(REWRITES[j][0], REWRITES[j][1]);
        break;
      }}
    }}
    return q.replace(/\\bbeginning\\s+with\\b/gi, "starting with");
  }}

  var api = {{ norm: norm, rewrite: rewrite }};
  if (typeof window !== "undefined") window.KrillionNorm = api;
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root) root.KrillionNorm = api;
}})(typeof globalThis !== "undefined" ? globalThis : this);
"""


def _write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8", newline="\n",
    )


def _table_exists(c: sqlite3.Connection, name: str) -> bool:
    return bool(
        c.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone()
    )


MATCHER_INDEX_JSON = "matcher_index.json"


def build_matcher_index(dest: Path | None = None) -> Path:
    """Build the derived matcher index from the stored bank questions.

    The question query and ordering are copied verbatim from
    injection/bridge.py, so a matcher loaded from this index is
    byte-identical to one built at bridge startup. The source hash of
    paraphrase_match.py is stored inside the index so the bridge can reject a
    stale artefact after the matcher algorithm changes.
    """
    dest = Path(dest) if dest is not None else cfg.DATA
    dest.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(f"file:{cfg.ONLY_DB.as_posix()}?mode=ro", uri=True) as c:
        questions = [r[0] for r in c.execute(
            "SELECT DISTINCT question FROM answers ORDER BY question"
        )]
    matcher = derive.pm.Matcher(questions)
    payload = matcher.to_index_dict(
        matcher_source_sha256=sha256_file(cfg.PARAPHRASE_SOURCE)
    )
    out = dest / MATCHER_INDEX_JSON
    _write_json(out, payload)
    return out


def _v2_payloads() -> dict[str, list]:
    """Array-JSON payloads from the materialisations (legacy fallback OK)."""
    nq = lambda q: derive.rewrite_query(derive.pm.normalise(q))
    with sqlite3.connect(
        f"file:{cfg.SEARCH_DB.as_posix()}?mode=ro", uri=True
    ) as c:
        table = "search_answer" if _table_exists(c, "search_answer") else "search_answers"
        search = [
            {"q": q, "nq": nq(q), "a": a}
            for q, a in c.execute(
                f"SELECT question, answer FROM {table} ORDER BY question"
            )
        ]
        if _table_exists(c, "krillion_answer"):
            rare = c.execute(
                "SELECT question, answer FROM krillion_answer ORDER BY question, answer"
            ).fetchall()
        else:
            with sqlite3.connect(
                f"file:{cfg.ONLY_DB.as_posix()}?mode=ro", uri=True
            ) as only:
                rare = only.execute(
                    "SELECT question, answer FROM answers ORDER BY question, answer"
                ).fetchall()
    grouped: dict[str, list[str]] = {}
    for q, a in rare:
        grouped.setdefault(q, []).append(a)
    krillion = [{"q": q, "nq": nq(q), "answers": grouped[q]} for q in sorted(grouped)]
    return {cfg.V2_SEARCH_JSON: search, cfg.V2_KRILLION_JSON: krillion}


# ---------------------------------------------------------------------------
# God-mode low-tier snapshot (see injection/GOD-PRELOAD-CONTRACT.md, frozen).
# The rows mirror bridge.tier_answers()'s fallback SQL, with exact DEEP CUT
# answers from learned.jsonl merged ahead of them. Nothing here writes to the
# Full DB or to any data log; the snapshot is a pure derived artefact.
# ---------------------------------------------------------------------------
TIER_ANSWER_LIMIT = 20
_TIER_SQL = (
    "SELECT answer FROM answers INDEXED BY idx_answers_question "
    "WHERE question=? AND is_krillion=0 "
    "ORDER BY answer COLLATE NOCASE LIMIT 20"
)
_TIER_BY_TEXT = {
    "PLANKTON": 10, "TOO CLEVER": 15, "SCHOOLER": 30,
    "RARE": 60, "DEEP CUT": 85, "ONE IN A KRILLION": 100,
}


def _grade(rec: dict) -> int | None:
    """The six-grade point value of a learned.jsonl record, if graded.

    tierIndex takes priority, then tier text, then the points field — the same
    order as injection/GOD-DISTRIBUTION.md. Ungraded records return None and
    are treated exactly like any other unknown low answer.
    """
    idx = rec.get("tierIndex")
    if isinstance(idx, bool):
        idx = None
    if isinstance(idx, int) and 0 <= idx <= 5:
        return cfg.TIER_POINTS[idx]
    if isinstance(idx, str) and idx.strip().isdigit() and int(idx) <= 5:
        return cfg.TIER_POINTS[int(idx)]
    tier = str(rec.get("tier") or "").strip().upper()
    for sep in ("-", "_"):
        tier = tier.replace(sep, " ")
    tier = " ".join(tier.split())
    if tier in _TIER_BY_TEXT:
        return _TIER_BY_TEXT[tier]
    points = rec.get("points")
    if isinstance(points, bool):
        return None
    if isinstance(points, int) and points in cfg.TIER_POINTS:
        return points
    if isinstance(points, str) and points.strip().isdigit():
        value = int(points)
        if value in cfg.TIER_POINTS:
            return value
    return None


def _learned_grades() -> dict[tuple[str, str], int]:
    """(question, answer) -> graded points; first graded row wins."""
    grades: dict[tuple[str, str], int] = {}
    for rec in derive.read_jsonl(cfg.LEARNED):
        points = _grade(rec)
        if points is not None:
            grades.setdefault((rec.get("question"), rec.get("answer")), points)
    return grades


def _krillion_pairs() -> set[tuple[str, str]]:
    """(question, answer) rows explicitly graded as 100 in the Full DB."""
    with sqlite3.connect(f"file:{cfg.FULL_DB.as_posix()}?mode=ro", uri=True) as c:
        return set(c.execute(
            "SELECT question, answer FROM answers WHERE is_krillion=1"
        ))


def _answer_points(question, answer, grades, krillion) -> int | None:
    # Learned grades win over the archive flag; unknown low answers stay null
    # (the userscript maps null onto the 85pt Deep Cut bucket).
    graded = grades.get((question, answer))
    if graded is not None:
        return graded
    return 100 if (question, answer) in krillion else None


def _exact_deepcut() -> dict[str, list[str]]:
    """question -> exact 85-point answers, in learned.jsonl order.

    The tier predicate is copied verbatim from bridge.tier_answers(). Empty
    answers are dropped there too, so drop them here as well.
    """
    by_question: dict[str, list[str]] = {}
    for rec in derive.read_jsonl(cfg.LEARNED):
        if not (
            rec.get("tierIndex") == 4
            or rec.get("tier") == "DEEP CUT"
            or rec.get("points") == 85
        ):
            continue
        answer = rec.get("answer", "")
        if not answer:
            continue
        by_question.setdefault(rec.get("question"), []).append(answer)
    return by_question


def tier_rows() -> list[list]:
    """Build the deterministic [[question, [[answer, points], ...]], ...] rows.

    Answer selection is unchanged from schema 1 (DB fallback order plus exact
    DEEP CUT answers first, deduped, capped at 20); only the point tags are new.
    """
    exact = _exact_deepcut()
    grades = _learned_grades()
    krillion = _krillion_pairs()
    with sqlite3.connect(f"file:{cfg.FULL_DB.as_posix()}?mode=ro", uri=True) as c:
        questions = [r[0] for r in c.execute(
            "SELECT DISTINCT question FROM answers WHERE is_krillion=0 ORDER BY question"
        )]
        rows = []
        for question in questions:
            db_answers = [a for (a,) in c.execute(_TIER_SQL, (question,))]
            merged: list[str] = []
            seen: set[str] = set()
            for answer in exact.get(question, []) + db_answers:
                if answer not in seen:
                    seen.add(answer)
                    merged.append(answer)
            tagged = [
                [answer, _answer_points(question, answer, grades, krillion)]
                for answer in merged[:TIER_ANSWER_LIMIT]
            ]
            rows.append([question, tagged])
    return rows


def build_tier_data(dest: Path | None = None, version: int | None = None) -> Path:
    """Write data/tier-data.json into dest (and its runtime location)."""
    dest = Path(dest) if dest is not None else cfg.STAGING
    dest.mkdir(parents=True, exist_ok=True)
    if version is None:
        version = next_data_version()
    payload = {
        "schema": cfg.TIER_SCHEMA_VERSION,
        "version": int(version),
        "rows": tier_rows(),
    }
    out = dest / cfg.TIER_DATA_JSON
    _write_json(out, payload)
    # publish.py only moves the four web artefacts; mirror to runtime data/ so
    # the bridge (and verify) can read the snapshot without a publish step.
    runtime = cfg.TIER_DATA
    if runtime.resolve() != out.resolve():
        runtime.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(out, runtime)
    print(
        f"emitted {cfg.TIER_DATA_JSON} schema={payload['schema']} "
        f"version={payload['version']} rows={len(payload['rows'])} "
        f"bytes={out.stat().st_size} -> {out}"
    )
    return out


def emit(out_dir: Path | None = None) -> dict:
    """Write manifest, generated JS and v2 arrays into out_dir (staging)."""
    out_dir = Path(out_dir) if out_dir is not None else cfg.STAGING
    out_dir.mkdir(parents=True, exist_ok=True)

    payloads = _v2_payloads()
    for name, data in payloads.items():
        _write_json(out_dir / name, data)

    version = next_data_version()
    tier_path = build_tier_data(out_dir, version=version)

    js = out_dir / cfg.NORM_JS.relative_to(cfg.ROOT)
    js.parent.mkdir(parents=True, exist_ok=True)
    js.write_text(generated_norm_js(), encoding="utf-8", newline="\n")

    index_path = build_matcher_index(out_dir)
    # The bridge reads the index from data/ at startup. Publish a copy there
    # too: publish.py only moves the four web artefacts, so without this a
    # normal `build all` would leave the manifest pointing at an index that
    # never reached its runtime location.
    runtime_index = cfg.DATA / MATCHER_INDEX_JSON
    if runtime_index.resolve() != index_path.resolve():
        runtime_index.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(index_path, runtime_index)

    counts = derive.counts()
    artifacts = {
        MATCHER_INDEX_JSON: sha256_file(index_path),
        cfg.TIER_DATA_JSON: sha256_file(tier_path),
        cfg.LEGACY_SEARCH_JSON: file_digest(cfg.ROOT / cfg.LEGACY_SEARCH_JSON),
        cfg.LEGACY_KRILLION_JSON: file_digest(cfg.ROOT / cfg.LEGACY_KRILLION_JSON),
        cfg.V2_SEARCH_JSON: sha256_file(out_dir / cfg.V2_SEARCH_JSON),
        cfg.V2_KRILLION_JSON: sha256_file(out_dir / cfg.V2_KRILLION_JSON),
        cfg.NORM_JS.relative_to(cfg.ROOT).as_posix(): sha256_file(js),
    }
    manifest = {
        "schema_version": cfg.SCHEMA_VERSION,
        "data_version": version,
        "etag": etag(),
        "built_at": cfg.utc_now(),
        "counts": {k: counts[k] for k in ("full", "search", "krillion", "prompts")},
        "artifacts": artifacts,
    }
    staged_manifest = out_dir / cfg.MANIFEST.relative_to(cfg.ROOT)
    _write_json(staged_manifest, manifest)
    # The bridge reads the manifest from data/ at runtime; publish.py moves the
    # staged copy there only on `all`. Mirror it here as well so a plain `emit`
    # leaves a readable manifest (including the tier sha) in place.
    if cfg.MANIFEST.resolve() != staged_manifest.resolve():
        cfg.MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(staged_manifest, cfg.MANIFEST)
    print(
        f"emitted manifest data_version={manifest['data_version']} "
        f"etag={manifest['etag'][:12]} counts={manifest['counts']} -> {out_dir}"
    )
    return manifest


